def initialize(c, now):
    if not c.execute("SELECT 1 FROM app_migrations WHERE name='idle_time_faq_v1'").fetchone():
        article=next(a for a in ARTICLES if a[0]==8)
        c.execute('INSERT INTO knowledge VALUES(?,?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET body=excluded.body,updated_at=excluded.updated_at',(*article,now()))
        c.execute("INSERT INTO app_migrations VALUES('idle_time_faq_v1')")
    # Versioned replacement only updates our shipped demo articles once.
    migration = 'grounded_hr_faq_v2'
    if c.execute('SELECT 1 FROM app_migrations WHERE name=?', (migration,)).fetchone():
        return
    for article in ARTICLES:
        c.execute('INSERT INTO knowledge VALUES(?,?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET '
                  'title=excluded.title,section=excluded.section,body=excluded.body,keywords=excluded.keywords,'
                  'roles=excluded.roles,updated_at=excluded.updated_at', (*article, now()))
    # Keep the original onboarding course consistent with sequential approvals.
    # Lesson count and correct answer indices stay unchanged; progress is retained.
    course = c.execute('SELECT * FROM courses WHERE id=1').fetchone()
    if course and course['title'] == 'Первый день в Jana Post':
        lessons, quiz = json.loads(course['lessons']), json.loads(course['quiz'])
        if len(lessons) == 3 and len(quiz) == 3:
            lessons[1]['body'] = ('В HR-сервисах выберите тип и даты отпуска и отправьте заявку. '
                                  'Сначала её согласует руководитель, затем HR. После обоих согласований '
                                  'приходит итоговое уведомление. Статус и история доступны в «Моих заявках».')
            quiz[1]['options'][1] = 'Сначала руководитель, затем HR'
            c.execute('UPDATE courses SET lessons=?,quiz=? WHERE id=1',
                      (json.dumps(lessons, ensure_ascii=False), json.dumps(quiz, ensure_ascii=False)))
    c.execute('INSERT INTO app_migrations VALUES(?)', (migration,))


def normalize(text):
    text = text.lower().replace('ё', 'е').strip()
    text = re.sub(r'[?!.,:;«»"—–]+', ' ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    text = re.sub(r'^(?:привет|здравствуйте|добрый день|салем)\s+', '', text)
    text = re.sub(r'^(?:подскажи(?:те)?|расскажи(?:те)?|скажи(?:те)?)\s+', '', text)
    text = re.sub(r'\bпожалуйста\b', '', text)
    return re.sub(r'\s+', ' ', text).strip()


