def respond(c, u, question, public_user, course_data, learning_stats, statuses):
    q = normalize(question)
    base = {'sources': [], 'kind': 'assistant'}

    def unknown():
        # No automatic dispatch; the UI opens the HR chat for an explicit message.
        hr = c.execute("SELECT id,name FROM users WHERE role='hr' AND id!=? ORDER BY id LIMIT 1", (u['id'],)).fetchone()
        return {**base, 'kind': 'clarify', 'answer':
                'В подготовленной базе знаний нет надежного ответа на этот вопрос. '
                'Я не буду предполагать кадровые правила. Уточните вопрос или обратитесь к HR.',
                'escalation': dict(hr) if hr else None}

    if re.search(r'парол|секрет|токен|паспорт|\bиин\b|зарплат', q):
        return {**base, 'kind': 'restricted', 'answer':
                'Я не выдаю пароли, секреты и персональные финансовые данные. По кадровому вопросу можно обратиться в HR.',
                'escalation': unknown()['escalation']}
    if q in ('привет', 'здравствуйте', 'добрый день', 'салем'):
        return {**base, 'answer': f'Здравствуйте, {u["name"].split()[0]}! Помогу с вашими заявками, обучением '
                'и документами. Отвечаю по подготовленным материалам и показываю источник.'}

    # Explicit message intent is kept separate from knowledge lookup. Ambiguous
    # recipients never cause a send; confirmation is required by the action API UI.
    command = re.match(r'^(?:напиши|отправь сообщение|сообщи)\s+(.+)$', question.strip(), re.I)
    if command:
        text = command[1]
        split = re.split(r':|,?\s+что\s+', text, maxsplit=1, flags=re.I)
        if len(split) != 2 or not split[1].strip():
            return {**base, 'kind': 'clarify', 'answer': 'Укажите получателя и текст через двоеточие: «Напиши Санжару: отчёт готов».'}
        name, body = split[0].strip().lower(), split[1].strip()
        people = c.execute('SELECT id,name FROM users WHERE id!=?', (u['id'],)).fetchall()
        matches = [p for p in people if any(re.fullmatch(re.escape(part.lower()) + r'(?:у|е|ой|и)?', word)
                   for part in p['name'].split() for word in name.split())]
        if len(matches) != 1:
            return {**base, 'kind': 'clarify', 'answer': 'Получатель не определён однозначно. Укажите имя и фамилию или выберите коллегу в Сообщениях.'}
        target = matches[0]
        return {**base, 'kind': 'confirm_action', 'answer': f'Подготовлено сообщение для {target["name"]}: «{body}». Отправить?',
                'action': {'type': 'send_message', 'recipient_id': target['id'], 'recipient_name': target['name'], 'body': body}}

    intent = next((key for key, patterns in PATTERNS.items() if any(re.fullmatch(p, q) for p in patterns)), None)
    if intent is None:
        return unknown()
    if isinstance(intent, int):
        article = c.execute('SELECT * FROM knowledge WHERE id=?', (intent,)).fetchone()
        if not article or u['role'] not in article['roles'].split(','):
            return unknown()
        return {**base, 'answer': article['body'], 'sources': [{'id': article['id'], 'title': article['title']}],
                'open': {1:'services', 2:'academy', 3:'profile', 4:'notifications', 5:'messages',
                         6:'approvals', 7:'documents', 8:'office', 9:'academy'}[intent]}

    me = public_user(c, u)
    page, title = {'balance': ('profile', 'Мой профиль · остаток отпуска'),
                   'requests': ('services', 'HR-сервисы · мои заявки'),
                   'courses': ('academy', 'Jana Academy · мои назначения и результат'),
                   'documents': ('documents', 'Мои документы'),
                   'shift': ('profile', 'Мой профиль · история смен'),
                   'profile': ('profile', 'Мой кадровый профиль'),
                   'directory': ('directory', 'Коллеги · рабочий справочник')}[intent]
    if intent == 'balance':
        answer = f'У вас {me["vacation_days"]} дней ежегодного отпуска: {me["reserved_days"]} зарезервировано, {me["available_days"]} доступно для новой заявки.'
    elif intent == 'requests':
        records = c.execute('SELECT start_date,end_date,status FROM requests WHERE user_id=? ORDER BY id DESC LIMIT 5', (u['id'],)).fetchall()
        answer = 'Ваши последние заявки: ' + '; '.join(f'{r["start_date"]}–{r["end_date"]}: {statuses.get(r["status"], r["status"])}' for r in records) if records else 'У вас пока нет заявок. Создать заявку можно в HR-сервисах.'
    elif intent == 'courses':
        active = [x['title'] for x in course_data(c, u['id']) if x['assigned'] and not x['completed_at']]
        stats = learning_stats(c, u['id'])
        answer = f'Ваш учебный уровень — {stats["level"]}/10, накоплено {stats["xp"]} XP. ' + ('Вам назначены незавершённые курсы: ' + '; '.join(active) + '.' if active else 'Все назначенные курсы завершены.')
    elif intent == 'documents':
        count = c.execute('SELECT count(*) FROM employee_documents WHERE user_id=?', (u['id'],)).fetchone()[0]
        answer = f'В разделе «Мои документы» у вас {count} файлов. Откройте источник, чтобы посмотреть документы и портфолио.'
    elif intent == 'shift':
        shift = c.execute('SELECT * FROM work_shifts WHERE user_id=? ORDER BY id DESC LIMIT 1', (u['id'],)).fetchone()
        answer = (f'Последняя сохранённая запись смены: {shift["started_at"][:16].replace("T", " ")}. '
                  f'Учтено {int(shift["work_seconds"]//3600):02}:{int(shift["work_seconds"]%3600//60):02} рабочего времени. '
                  'Текущий таймер находится на карте; завершённые смены — в профиле.') if shift else 'История смен пока пуста. Начать работу можно на карте офиса.'
    elif intent == 'profile':
        answer = f'Вы — {u["name"]}, {u["position"]}, подразделение «{u["department"]}». Руководитель: {me["manager_name"]}.'
    else:
        answer = 'В «Коллегах» доступны рабочие карточки сотрудников. Откройте карточку и нажмите «Написать сообщение», чтобы начать внутренний чат.'
    return {**base, 'answer': answer, 'sources': [{'id': 'profile' if page == 'profile' else intent, 'page': page, 'title': title}], 'open': page}
